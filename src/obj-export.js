export function wavefrontStem(name) {
    const basename = String(name || "").split(/[\\/]/).pop().replace(/\.[^.]*$/, "");
    return basename.replace(/[^A-Za-z0-9_-]+/g, "_").replace(/^_+|_+$/g, "").slice(0, 100) || "model";
}

function finite(value, label) {
    if (typeof value !== "number" || !Number.isFinite(value) || !Number.isFinite(Math.fround(value))) {
        throw new TypeError(`${label} must be a finite 32-bit number`);
    }
    return Object.is(value, -0) ? 0 : value;
}

function vector(values, size, label) {
    if (!values || values.length !== size) throw new TypeError(`${label} must have ${size} components`);
    return Array.from(values, (value, index) => finite(value, `${label}[${index}]`));
}

function texturePath(name) {
    if (!name) return "";
    if (typeof name !== "string") throw new TypeError("Texture name must be a string");
    const basename = name.split(/[\\/]/).pop().replace(/[\x00-\x1f\x7f#]/g, "_").trim();
    if (!basename || basename === "." || basename === "..") throw new Error("Invalid texture filename");
    return `texture/${basename}`;
}

/** Serialize one scene model in the same local coordinates as the desktop exporter. */
export function exportWavefront(model) {
    if (!model || !(model.vertices instanceof Float32Array) || model.vertices.length % 8 ||
        !(model.triangles instanceof Uint32Array) || model.triangles.length % 4 ||
        !Array.isArray(model.materials)) throw new TypeError("Invalid model arrays");
    const stem = wavefrontStem(model.name);
    const obj = ["# Generated by O3DView Web", `mtllib ${stem}.mtl`, "s 0", ""];
    const positions = [], uvs = [], normals = [];
    for (let i = 0; i < model.vertices.length; i += 8) {
        const v = Array.from(model.vertices.subarray(i, i + 8), (value, j) => finite(value, `Vertex ${i / 8} component ${j}`));
        positions.push(`v ${-v[0]} ${v[1]} ${v[2]}`);
        uvs.push(`vt ${v[6]} ${finite(1 - v[7], "Flipped UV")}`);
        normals.push(`vn ${-v[3]} ${v[4]} ${v[5]}`);
    }
    obj.push(positions.join("\n"), "", uvs.join("\n"), "", normals.join("\n"), "");
    let lastMaterial = -1;
    for (let i = 0; i < model.triangles.length; i += 4) {
        const [a, b, c, material] = model.triangles.subarray(i, i + 4);
        if (a >= positions.length || b >= positions.length || c >= positions.length || material >= model.materials.length) {
            throw new RangeError(`Triangle ${i / 4} references an invalid vertex or material`);
        }
        if (material !== lastMaterial) {
            obj.push(`g matl_${material}`, `usemtl matl_${material}`);
            lastMaterial = material;
        }
        const ref = index => `${index + 1}/${index + 1}/${index + 1}`;
        obj.push(`f ${ref(c)} ${ref(b)} ${ref(a)}`);
    }
    const mtl = ["# Generated by O3DView Web", ""];
    for (const [i, material] of model.materials.entries()) {
        if (!material) throw new TypeError(`Material ${i} is missing`);
        const diffuse = vector(material.diffuse, 4, `Material ${i} diffuse`);
        const spec = vector(material.spec, 3, `Material ${i} specular`);
        const emission = vector(material.emission, 3, `Material ${i} emission`);
        const power = finite(material.specPower, `Material ${i} specular power`);
        const texture = texturePath(material.repaintTextureName || material.textureName);
        mtl.push(`newmtl matl_${i}`, `Ka ${diffuse.slice(0, 3).join(" ")}`, `Kd ${diffuse.slice(0, 3).join(" ")}`,
            `Ks ${spec.join(" ")}`, `Ns ${Math.min(1000, Math.max(0, power))}`, `Ke ${emission.join(" ")}`,
            `d ${diffuse[3]}`);
        if (diffuse[3] !== 1) mtl.push(`Tr ${finite(1 - diffuse[3], "Transparency")}`);
        mtl.push("illum 2");
        if (texture) mtl.push(`map_Kd ${texture}`);
        mtl.push("");
    }
    return { obj: `${obj.join("\n")}\n`, mtl: `${mtl.join("\n")}\n`, objName: `${stem}.obj`, mtlName: `${stem}.mtl` };
}

/** Combine scene occurrences, preserving the already-applied placement of each model. */
export function combineSceneModels(models, name = "scene.obj") {
    if (!Array.isArray(models) || !models.length) throw new Error("No scene models to export");
    let vertexCount = 0, triangleComponents = 0, materialCount = 0;
    for (const model of models) {
        if (!model || !(model.vertices instanceof Float32Array) || model.vertices.length % 8 ||
            !(model.triangles instanceof Uint32Array) || model.triangles.length % 4 ||
            !Array.isArray(model.materials)) throw new TypeError("Invalid model arrays");
        vertexCount += model.vertices.length / 8;
        triangleComponents += model.triangles.length;
        materialCount += model.materials.length;
        if (!Number.isSafeInteger(vertexCount) || vertexCount > 0xffffffff ||
            !Number.isSafeInteger(triangleComponents) || !Number.isSafeInteger(materialCount) || materialCount > 0xffffffff) {
            throw new RangeError("Scene is too large to export");
        }
    }
    const vertices = new Float32Array(vertexCount * 8);
    const triangles = new Uint32Array(triangleComponents);
    const materials = [];
    let vertexOffset = 0, triangleOffset = 0, materialOffset = 0;
    for (const model of models) {
        vertices.set(model.vertices, vertexOffset * 8);
        for (let i = 0; i < model.triangles.length; i += 4) {
            const [a, b, c, material] = model.triangles.subarray(i, i + 4);
            if (a >= model.vertices.length / 8 || b >= model.vertices.length / 8 ||
                c >= model.vertices.length / 8 || material >= model.materials.length) {
                throw new RangeError(`Triangle ${i / 4} in ${model.name || "model"} references an invalid vertex or material`);
            }
            triangles[triangleOffset++] = a + vertexOffset;
            triangles[triangleOffset++] = b + vertexOffset;
            triangles[triangleOffset++] = c + vertexOffset;
            triangles[triangleOffset++] = material + materialOffset;
        }
        for (const material of model.materials) materials.push(material);
        vertexOffset += model.vertices.length / 8;
        materialOffset += model.materials.length;
    }
    return { name, vertices, triangles, materials };
}

/** Download one member of the pair; separate clicks avoid multiple-download blocking. */
export function downloadWavefront(model, format, documentObject = document, url = URL) {
    if (format !== "obj" && format !== "mtl") throw new Error("Unknown Wavefront download format");
    const result = exportWavefront(model);
    const href = url.createObjectURL(new Blob([result[format]], { type: "text/plain;charset=utf-8" }));
    try {
        const link = documentObject.createElement("a");
        link.href = href;
        link.download = result[`${format}Name`];
        link.click();
    } finally {
        setTimeout(() => url.revokeObjectURL(href), 1000);
    }
    return result[`${format}Name`];
}
